const dict: Record<Lang, Record<string, string>> = { es, en };

export function translate(lang: Lang, key: string, params?: Params): string {
  let str = dict[lang][key] ?? dict.es[key] ?? key;
  if (params) {
    for (const k of Object.keys(params)) {
      str = str.replace(`{${k}}`, String(params[k]));
    }
  }
  return str;
}

/** Tipos de cocina con traducción conocida (vocabulario acotado del catálogo). */
const KNOWN_CUISINES = ['italian', 'asian', 'fusion', 'american', 'burgers', 'pizza', 'sushi'];

/**
 * Traduce un tipo de cocina que viene de la BD. Si es un valor conocido usa su
 * clave i18n; si no, devuelve el texto original tal cual lo escribió el
 * restaurante (el texto libre del catálogo no se traduce).
 */
export function cuisineLabel(t: (key: string) => string, raw: string): string {
  const k = raw.trim().toLowerCase();
  return KNOWN_CUISINES.includes(k) ? t(`cuisine.${k}`) : raw;
}
